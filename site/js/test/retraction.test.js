// Tests for retraction.js, on G-code written the way PrusaSlicer 2.9 writes it (GCodeWriter:
// retract = "G1 E-.8 F2100", unretract = "G1 E.8 F1500", wipe = "G1 X.. Y.. E-.. F.." between
// ;WIPE_START and ;WIPE_END, G92 E0 at each layer change, absolute or relative E). Run:
//   node hexcalibr/site/js/test/retraction.test.js [real.gcode ...]
// Real files given as arguments are rewritten and checked with the same independent checker.
'use strict';
var fs = require('fs');
var path = require('path');
var R = require(path.join(__dirname, '..', 'retraction.js'));

var failures = 0;
function ok(cond, msg) { if (!cond) { failures++; console.log('FAIL ' + msg); } else { console.log('ok   ' + msg); } }

var DD = [0, 0.2, 0.4, 0.6, 0.8, 1, 1.2, 1.4, 1.6, 1.8, 2];
function marker(lengths, radius) {
  return ';HEXCALIBR retraction v1 lengths=' + lengths.map(function (v) { return v.toFixed(1); }).join(',') +
    ' radius=' + radius.toFixed(3) + ' front=-90 pitch=20';
}

// A PrusaSlicer-like G-code for the ring. o: {absE, wipe, layerRetract, extra, L, dx, dy, rot,
// chainStart, layers, skirt, lengths}
function simulate(o) {
  var lengths = o.lengths || DD;
  var n = lengths.length, R0 = 20 / (2 * Math.sin(Math.PI / n));
  var L = o.L === undefined ? 0.8 : o.L, extra = o.extra || 0;
  var lines = [], E = 0;
  function e(v) {                          // emit an E word, absolute or relative
    if (o.absE) { E += v; return 'E' + R._num(E); }
    return 'E' + R._num(v);
  }
  function pillar(k) {
    var a = (-90 + k * 360 / n + (o.rot || 0)) * Math.PI / 180;
    return [(o.dx || 150) + R0 * Math.cos(a), (o.dy || 150) + R0 * Math.sin(a)];
  }
  function hexLoop(c, r, start) {         // a loop around the pillar starting near `start`
    var a0 = Math.atan2(start[1] - c[1], start[0] - c[0]);
    var pts = [];
    for (var j = 0; j <= 6; j++) { var a = a0 + j * Math.PI / 3; pts.push([c[0] + r * Math.cos(a), c[1] + r * Math.sin(a)]); }
    return pts;
  }
  function fmt(v) { return R._num(v); }
  function retract() {
    if (o.wipe) {
      lines.push(';WIPE_START');
      lines.push('G1 F8640');
      lines.push('G1 X' + fmt(pos[0] + 1) + ' Y' + fmt(pos[1]) + ' ' + e(-L * 0.6));
      lines.push('G1 X' + fmt(pos[0] + 1) + ' Y' + fmt(pos[1] + 0.5) + ' ' + e(-L * 0.2));
      lines.push(';WIPE_END');
      lines.push('G1 ' + e(-L * 0.2) + ' F2100');
    } else {
      lines.push('G1 ' + e(-L) + ' F2100');
    }
  }
  function unretract() { lines.push('G1 ' + e(L + extra) + ' F1500'); }
  lines.push('; generated by PrusaSlicer 2.9.0 (test simulation)');
  lines.push('M73 P0 R10');
  lines.push(o.absE ? 'M82' : 'M83');
  lines.push(';TYPE:Custom');
  lines.push('G1 X10 Y10 F9000');
  lines.push('G1 X100 Y10 ' + e(10) + ' F1200');   // purge line
  lines.push('G92 E0'); E = 0;
  var pos = [100, 10];
  // base layers: a few retracts that must not be touched
  for (var b = 0; b < 3; b++) {
    lines.push(';LAYER_CHANGE'); lines.push(';Z:' + (0.2 * (b + 1)).toFixed(1)); lines.push('G1 Z' + (0.2 * (b + 1)).toFixed(1));
    lines.push(';TYPE:External perimeter');
    retract(); lines.push('G1 X150 Y110 F9000'); pos = [150, 110]; unretract();
    lines.push('G1 X160 Y110 ' + e(0.5) + ' F1800'); pos = [160, 110];
  }
  var layers = o.layers || 5;
  var cs = o.chainStart || 0;
  for (var l = 0; l < layers; l++) {
    var z = (0.8 + 0.2 * l).toFixed(1);
    lines.push(';LAYER_CHANGE'); lines.push(';Z:' + z);
    if (o.layerRetract) { retract(); }
    lines.push('G1 Z' + z + ' F720');
    if (o.absE) { lines.push('G92 E0'); E = 0; }
    if (l === 0) { lines.push(';CUSTOM_GCODE'); lines.push(marker(lengths, R0)); }
    for (var s = 0; s < n; s++) {
      var k = (cs + s) % n;
      var c = pillar(k);
      var loop = hexLoop(c, 2.4, pos);
      if (!(o.layerRetract && s === 0)) { retract(); }
      lines.push('G1 X' + fmt(loop[0][0]) + ' Y' + fmt(loop[0][1]) + ' F12000');
      pos = loop[0];
      unretract();
      lines.push(';TYPE:External perimeter');
      for (var j = 1; j < loop.length; j++) {
        lines.push('G1 X' + fmt(loop[j][0]) + ' Y' + fmt(loop[j][1]) + ' ' + e(0.05));
        pos = loop[j];
      }
    }
  }
  lines.push(';TYPE:Custom');
  lines.push('G1 ' + (o.absE ? 'E' + R._num(E - 2) : 'E-2') + ' F2100');
  lines.push('G1 Z30');
  lines.push('M84');
  lines.push('; retract_length = ' + L);
  return lines.join('\n') + '\n';
}

// Independent check of a rewritten file: walk it, rebuild each retract event, find the pillars
// from the marker the same way a reader would (nearest expected centre after fitting the offset by
// the mean of the extrusion points), and compare with the gap's length.
function check(outText, inText, name) {
  var lines = outText.split('\n');
  var mi = lines.findIndex(function (l) { return l.indexOf(R.MARKER) === 0; });
  var ring = R.parseMarker(lines[mi]);
  var n = ring.lengths.length;
  var absE = false, E = 0, x = 0, y = 0, inRegion = false;
  var evs = [], cur = null, lastXY = null;
  var totalOut = 0;
  lines.forEach(function (ln, i) {
    if (i === mi) { inRegion = true; }
    if (/^;TYPE:Custom/.test(ln) && inRegion) { inRegion = false; }
    var code = ln.split(';')[0].trim();
    if (!code) { return; }
    var w = {};
    code.replace(/([A-Z])([-.\d]+)/g, function (_, k, v) { w[k] = Number(v); });
    var c = code.split(/\s/)[0];
    if (c === 'M82') { absE = true; } else if (c === 'M83') { absE = false; }
    if (c === 'G92' && 'E' in w) { E = w.E; return; }
    if (c !== 'G1' && c !== 'G0') { return; }
    var sx = x, sy = y;
    if ('X' in w) { x = w.X; } if ('Y' in w) { y = w.Y; }
    if (!('E' in w)) { return; }
    var de = absE ? w.E - E : w.E; if (absE) { E = w.E; }
    totalOut += de;
    if (!inRegion) { return; }
    var mv = 'X' in w || 'Y' in w;
    if (de < 0) { if (!cur) { cur = { from: lastXY, pull: 0 }; } cur.pull -= de; }
    else if (de > 0 && !mv && cur) { cur.push = de; cur.to = [x, y]; evs.push(cur); cur = null; }
    else if (de > 0 && mv) { lastXY = [x, y]; }
  });
  return { events: evs, ring: ring, total: totalOut };
}

function totalE(text) {
  var absE = false, E = 0, tot = 0;
  text.split('\n').forEach(function (ln) {
    var code = ln.split(';')[0].trim(); if (!code) { return; }
    var w = {}; code.replace(/([A-Z])([-.\d]+)/g, function (_, k, v) { w[k] = Number(v); });
    var c = code.split(/\s/)[0];
    if (c === 'M82') { absE = true; } else if (c === 'M83') { absE = false; }
    if (c === 'G92' && 'E' in w) { E = w.E; return; }
    if ((c === 'G1' || c === 'G0') && 'E' in w) { var de = absE ? w.E - E : w.E; if (absE) { E = w.E; } tot += de; }
  });
  return tot;
}

function centres(ring, text) {
  // expected centres from the marker, translated by the mean of the region's extrusion points
  var n = ring.lengths.length, pts = [], inR = false, x = 0, y = 0, absE = false, E = 0;
  text.split('\n').forEach(function (ln) {
    if (ln.indexOf(R.MARKER) === 0) { inR = true; }
    if (/^;TYPE:Custom/.test(ln) && inR) { inR = false; }
    var code = ln.split(';')[0].trim(); if (!code) { return; }
    var w = {}; code.replace(/([A-Z])([-.\d]+)/g, function (_, k, v) { w[k] = Number(v); });
    var c = code.split(/\s/)[0];
    if (c === 'M82') { absE = true; } else if (c === 'M83') { absE = false; }
    if (c === 'G92' && 'E' in w) { E = w.E; return; }
    if (c !== 'G1') { return; }
    if ('X' in w) { x = w.X; } if ('Y' in w) { y = w.Y; }
    if ('E' in w) { var de = absE ? w.E - E : w.E; if (absE) { E = w.E; } if (de > 0 && inR && ('X' in w)) { pts.push([x, y]); } }
  });
  var mx = 0, my = 0; pts.forEach(function (p) { mx += p[0]; my += p[1]; }); mx /= pts.length; my /= pts.length;
  var out = [];
  for (var k = 0; k < n; k++) { var a = (ring.front + k * 360 / n) * Math.PI / 180; out.push([mx + ring.radius * Math.cos(a), my + ring.radius * Math.sin(a)]); }
  return out;
}

function near(cs, p) {
  var best = -1, bd = 1e9;
  cs.forEach(function (c, k) { var d = Math.hypot(c[0] - p[0], c[1] - p[1]); if (d < bd) { bd = d; best = k; } });
  return bd < 5 ? best : -1;
}

function verify(name, input, opts) {
  opts = opts || {};
  var res;
  try { res = R.rewrite(input); } catch (err) { ok(false, name + ': threw ' + err.message); return null; }
  var chk = check(res.gcode, input, name);
  var cs = centres(chk.ring, res.gcode);
  var n = chk.ring.lengths.length, bad = 0, gapEvents = 0, perGap = new Array(n).fill(0);
  chk.events.forEach(function (ev) {
    if (!ev.from) { return; }
    var a = near(cs, ev.from), b = near(cs, ev.to);
    var gap = (a >= 0 && b >= 0 && (a + 1) % n === b) ? a : (a >= 0 && b >= 0 && (b + 1) % n === a) ? b : -1;
    if (gap < 0) { return; }
    gapEvents++; perGap[gap]++;
    var want = chk.ring.lengths[gap];
    if (Math.abs(ev.pull - want) > 2e-4) { bad++; if (bad < 4) { console.log('   gap ' + gap + ' pulled ' + ev.pull + ' want ' + want); } }
    if (Math.abs(ev.push - ev.pull - (opts.extra || 0)) > 2e-4 && want > 0) { bad++; if (bad < 4) { console.log('   gap ' + gap + ' push ' + ev.push + ' pull ' + ev.pull); } }
  });
  ok(bad === 0 && gapEvents > 0, name + ': ' + gapEvents + ' gap retractions, all at their gap\'s length' + (bad ? ' (' + bad + ' wrong)' : ''));
  // the checker cannot see a 0 mm gap (its moves are E0), the summary can
  ok(res.summary.perGap.every(function (c) { return c > 0; }) &&
     perGap.every(function (c, k) { return c > 0 || chk.ring.lengths[k] === 0; }),
     name + ': every gap rewritten (' + res.summary.perGap.join(' ') + ')');
  var tin = totalE(input), tout = totalE(res.gcode);
  ok(Math.abs(tin - tout) < 1e-3, name + ': net filament unchanged (' + tin.toFixed(4) + ' vs ' + tout.toFixed(4) + ')');
  ok(res.summary.rewritten === res.summary.perGap.reduce(function (a, b) { return a + b; }, 0), name + ': summary adds up');
  return res;
}

// --- synthetic cases -----------------------------------------------------------------------
var base = { layers: 6 };
verify('relative E', simulate(base));
verify('absolute E with G92 per layer', simulate({ layers: 6, absE: true }));
verify('wipe (60/20/20 split)', simulate({ layers: 6, wipe: true }));
verify('wipe + absolute E', simulate({ layers: 6, wipe: true, absE: true }));
verify('retract on layer change', simulate({ layers: 6, layerRetract: true }));
verify('layer change + absolute E', simulate({ layers: 6, layerRetract: true, absE: true }));
verify('restart extra 0.1', simulate({ layers: 6, extra: 0.1 }), { extra: 0.1 });
verify('chain starts mid-ring', simulate({ layers: 6, chainStart: 4 }));
verify('profile length 2.5', simulate({ layers: 6, L: 2.5 }));
var bow = [0, 0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5, 5.5, 6];
verify('bowden ring, 13 gaps', simulate({ layers: 6, lengths: bow, L: 3 }));

var r1 = R.rewrite(simulate(base));
// layers after the marker's own layer (the marker comes after its LAYER_CHANGE)
ok(r1.summary.fullLayers === 5 && r1.summary.layers === 5, 'every layer has all gaps (' + r1.summary.fullLayers + '/' + r1.summary.layers + ')');
ok(Math.abs(r1.summary.profileLength - 0.8) < 1e-9, 'profile length found: ' + r1.summary.profileLength);
ok(/\n;HEXCALIBR rewritten: /.test(r1.gcode), 'rewritten line added');
ok(r1.gcode.split('\n').slice(0, 30).join('\n') === simulate(base).split('\n').slice(0, 30).join('\n'), 'start G-code and base untouched');
ok(/\nG1 E-2 F2100\n/.test(r1.gcode), 'end G-code retract untouched');

// --- refusals ------------------------------------------------------------------------------
function refuses(name, text, code) {
  try { R.rewrite(text); ok(false, name + ': should refuse with ' + code); }
  catch (err) { ok(err.code === code, name + ': refused with ' + err.code); }
}
refuses('no marker', 'G1 X1 Y1\n', 'no_marker');
refuses('rewritten twice', r1.gcode, 'already');
refuses('length 0 in the profile', simulate({ layers: 3, L: 0 }), 'no_retracts');
refuses('firmware retraction', simulate({ layers: 3 }).replace(/G1 E-\.8 F2100/g, 'G10').replace(/G1 E\.8 F1500/g, 'G11'), 'firmware_retraction');
refuses('turned 90 degrees', simulate({ layers: 3, rot: 90 }), 'ring_mismatch');
refuses('turned 180 degrees', simulate({ layers: 3, rot: 180 }), 'ring_mismatch');

// --- real files ----------------------------------------------------------------------------
process.argv.slice(2).forEach(function (f) {
  var t = fs.readFileSync(f, 'utf8');
  var res = verify(path.basename(f), t);
  if (res) { console.log('     ' + JSON.stringify(res.summary)); }
});

console.log(failures ? failures + ' FAILED' : 'all tests passed');
process.exit(failures ? 1 : 0);
